import uuid

random_id = uuid.uuid4()


class AproxCoordsAdjuster:
  def __init__(
    self,
    project: Project,
    import_session: ImportSession,
    station_setup: StationSetup
  ):
    self.project = project
    self.import_session = import_session
    self.station_setup = station_setup

    self.references_bessel = self._get_references_bessel()
    self.desorientacion_estacionamiento = self.calculate_desorientacion_estacionamiento()
    self.cooordenadas_aproximadas = self.calculate_coordenadas_aproximadas()

  def _get_references_bessel(self) -> list[BesselObservation]:
    if not self.station_setup.bessel_observations or not self.project.reference_coordinates:
      raise ValueError("No se encontraron observaciones Bessel")

    reference_names = [ref.target_name for ref in self.project.reference_coordinates]

    return [
        obs for obs in self.station_setup.bessel_observations
        if obs.target_name in reference_names
    ]

  def _calculate_desorientacion_reference(
    self,
    reference: ReferenceCoordinate,
    bessel_reference: BesselObservation,
  ) -> float:
    if not self.station_setup.etr_x or not self.station_setup.etr_y:
      raise ValueError("No se encontraron coordenadas ETR")

    delta_x = reference.x - self.station_setup.etr_x
    delta_y = reference.y - self.station_setup.etr_y

    acimut = math.atan2(delta_x, delta_y) * self.project.gon_r
    acimut = acimut if acimut > 0.0 else acimut + 400.0

    desorientacion = acimut - bessel_reference.hz_angle_bessel

    return desorientacion if desorientacion > 0.0 else desorientacion + 400.0

  def _search_reference_by_target_name(self, target_name: str) -> ReferenceCoordinate:
    if not self.project.reference_coordinates:
      raise ValueError("No se encontraron referencias")

    for ref in self.project.reference_coordinates:
      if ref.target_name == target_name:
        return ref

    raise ValueError(f"No se encontró una referencia con el nombre {target_name}")

  def calculate_desorientacion_estacionamiento(self) -> float:
    if not self.project.reference_coordinates:
      raise ValueError("No se encontraron referencias")

    return statistics.mean(
      [
        self._calculate_desorientacion_reference(
            reference=self._search_reference_by_target_name(ref.target_name),
            bessel_reference=ref
        ) for ref in self.references_bessel
      ]
    )

  def _calculate_coordenada_aproximada(
    self, bessel_observation: BesselObservation
  ) -> ApproximateCoordinate:
    if not self.station_setup.etr_x or not self.station_setup.etr_y or not self.station_setup.etr_z or not self.station_setup.k_utm:
      raise ValueError

    w_cc = (
      bessel_observation.distance_bessel
      / self.project.radio_tierra
      * self.project.r_cc_adimensional
    )
    r_cc = self.import_session.kt_coef_refr * w_cc
    dist_reducida_horizonte_etr = (
      bessel_observation.distance_bessel
      * math.sin((bessel_observation.v_angle_bessel - w_cc + r_cc) * self.project.gon_r)
      / math.cos((w_cc / 2) * self.project.gon_r)
    )
    dist_reducida_elips = (
      dist_reducida_horizonte_etr
      * self.project.radio_tierra
      / (self.project.radio_tierra + self.station_setup.etr_z)
    )
    dist_utm = dist_reducida_elips * self.station_setup.k_utm
    acimut = (
      bessel_observation.hz_angle_bessel
      + self.desorientacion_estacionamiento
    )
    acimut_corr = acimut - 400 if acimut > 400 else acimut

    x = self.station_setup.etr_x + dist_utm * math.sin(acimut_corr * self.project.gon_r)
    y = self.station_setup.etr_y + dist_utm * math.cos(acimut_corr * self.project.gon_r)
    z = (
      bessel_observation.distance_bessel
      * math.cos(bessel_observation.v_angle_bessel * self.project.gon_r)
      + (0.5 - self.import_session.kt_coef_refr)
      * bessel_observation.distance_bessel**2
      / self.project.radio_tierra
      + self.station_setup.etr_z
    )

    return ApproximateCoordinate(
        id=random_id.int,
        target_name=bessel_observation.target_name,
        x=x,
        y=y,
        z=z
    )

  def calculate_coordenadas_aproximadas(self) -> list[ApproximateCoordinate]:
    if not self.station_setup.bessel_observations:
      raise ValueError("No se encontraron observaciones Bessel")

    return [
      self._calculate_coordenada_aproximada(bessel_observation)
      for bessel_observation in self.station_setup.bessel_observations
    ]


