import json
from dataclasses import asdict, is_dataclass
from datetime import datetime


def project_serializer(obj):
  if isinstance(obj, datetime):
    return obj.isoformat()

  if isinstance(obj, bytes):
    return obj.hex()

  if isinstance(obj, property):
    return str(obj)

  raise TypeError(f"El tipo{type(obj)} no es serializable a JSON")


def export_project_to_json(project: Project, filename: str | None = None):
  project_dict = asdict(project)

  json_str = json.dumps(project_dict, default=project_serializer, indent=4, ensure_ascii=False)

  if filename:
    with open(filename, 'w', encoding='utf-8') as f:
      f.write(json_str)
  else:
    print(json_str)


