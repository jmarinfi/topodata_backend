class BesselAdjuster:
  def __init__(self, station_setup: StationSetup):
    self.station_setup = station_setup

    self.df_observations: pd.DataFrame = self._to_df()
    self.bessel_observations: list[BesselObservation] = self.adjust_bessel()

  def _to_df(self):
    observations = self.station_setup.raw_observations
    if not observations:
      print(f'No hay observaciones brutas en el estacionamiento: {self.station_setup.station_name}')
      return pd.DataFrame()

    data = [
      asdict(observation)
      for observation in observations
    ]
    df = pd.DataFrame(data)

    return df

  def adjust_bessel(self) -> list[BesselObservation]:
    df = self.df_observations[
      (self.df_observations["v_angle"] != 0)
      & (self.df_observations["distance_geom"] != 0)
    ].copy()

    target_names_unique = df["target_name"].unique()
    df_bessel = pd.DataFrame()

    for target_name in target_names_unique:
      hz_angle_directo = df[
          (df["target_name"] == target_name) & (df["circle"] == 1)
      ]["hz_angle"]
      v_angle_directo = df[
          (df["target_name"] == target_name) & (df["circle"] == 1)
      ]["v_angle"]
      distance_directo = df[
          (df["target_name"] == target_name) & (df["circle"] == 1)
      ]["distance_geom"]
      hz_angle_inverso = df[
          (df["target_name"] == target_name) & (df["circle"] == 2)
      ]["hz_angle"]
      v_angle_inverso = df[
          (df["target_name"] == target_name) & (df["circle"] == 2)
      ]["v_angle"]
      distance_inverso = df[
          (df["target_name"] == target_name) & (df["circle"] == 2)
      ]["distance_geom"]
      v_angle_inverso = df[
          (df["target_name"] == target_name) & (df["circle"] == 2)
      ]["v_angle"]
      distance_inverso = df[
          (df["target_name"] == target_name) & (df["circle"] == 2)
      ]["distance_geom"]

      if (
          hz_angle_directo.empty
          or hz_angle_inverso.empty
          or v_angle_directo.empty
          or v_angle_inverso.empty
          or distance_directo.empty
          or distance_inverso.empty
      ):
          print(f"No hay datos para {target_name}")
          continue

      data_bessel = {
          "target_name": target_name,
          "hz_angle_direct": hz_angle_directo.mean(),
          "v_angle_direct": v_angle_directo.mean(),
          "distance_direct": distance_directo.mean(),
          "hz_angle_inverse": hz_angle_inverso.mean(),
          "v_angle_inverse": v_angle_inverso.mean(),
          "distance_inverse": distance_inverso.mean(),
      }
      df_bessel = pd.concat(
          [df_bessel, pd.DataFrame([data_bessel])], ignore_index=True
      )

    df_bessel["hz_angle_bessel"] = (
      df_bessel["hz_angle_direct"]
      + df_bessel["hz_angle_inverse"]
      + np.where(df_bessel["hz_angle_direct"] < 200, -200, 200)
    ) / 2
    df_bessel["v_angle_bessel"] = (
      df_bessel["v_angle_direct"]
      - (df_bessel["v_angle_direct"] + df_bessel["v_angle_inverse"] - 400) / 2
    )
    df_bessel["distance_bessel"] = df_bessel[
      ["distance_direct", "distance_inverse"]
    ].mean(axis=1)
    df_bessel["hz_angle_delta"] = (
      df_bessel["hz_angle_inverse"]
      - df_bessel["hz_angle_direct"]
      + np.where(df_bessel["hz_angle_direct"] < 200, -200, 200)
    )
    df_bessel["v_angle_delta"] = (
      df_bessel["v_angle_direct"] - df_bessel["v_angle_bessel"]
    ) * 2
    df_bessel["distance_delta"] = (
      df_bessel["distance_bessel"] - df_bessel["distance_direct"]
    ) * 2

    df_bessel = df_bessel.dropna(
      subset=[
        "hz_angle_bessel",
        "v_angle_bessel",
        "distance_bessel",
        "hz_angle_delta",
        "v_angle_delta",
        "distance_delta",
      ]
    )
    records = df_bessel.to_dict(orient="records")

    return [
        BesselObservation(
            id=random_id.int,
            **{k: v for k, v in record.items() if isinstance(k, str)}
        )
        for record in records
    ]


