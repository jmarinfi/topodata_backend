"""### Implementación del Analizador (Parser) GKA
La clase `GkaParser` se encarga de procesar los archivos de texto con formato GKA:
*   **_read_file**: Lectura del contenido físico del archivo.
*   **parse**: El método principal que itera por cada línea, identifica los bloques de estación (marcados por `#GNV11` y `#END11`) y extrae las columnas de datos para instanciar objetos `StationSetup` y `RawObservation`. Incluye manejo de errores básico para convertir cadenas de texto a valores numéricos.
"""

from pathlib import Path
import uuid
import hashlib

random_id = uuid.uuid4()


class GkaParser:

  def __init__(self, file: Path) -> None:
    self.file = file
    self.content = self._read_file()
    self.lines = self.content.splitlines()

  def _read_file(self) -> str:
    with open(self.file, 'r') as f:
      return f.read()

  def parse(self, project: Project) -> tuple[ImportSession, list[StationSetup]] | None:
    station_setups: list[StationSetup] = []
    current_station: StationSetup | None = None
    is_new_station: bool = False

    import_session = ImportSession(
        id=random_id.int,
        filename=self.file.name,
        content_hash=hashlib.md5(self.content.encode()).hexdigest(),
        raw_file_content=self.content
    )

    try:
      for line in self.lines:
        line = line.strip()
        if not line:
          continue

        # Flag de inicio de estacionamiento
        if line.startswith('#GNV11'):
          is_new_station = True
          current_station = None
          continue

        # Flag de fin de estacionamiento
        if line.startswith('#END11'):
          is_new_station = False
          current_station = None
          continue

        columns = line.split(',')

        # Inicio del parseo del estacionamiento
        if is_new_station:
          current_station = StationSetup(
              id=random_id.int,
              station_name=columns[1].strip()
          )

          if len(columns) > 5:
            try:
              current_station.station_height = float(columns[5].strip())
            except Exception:
              current_station.station_height = None

          if len(columns) > 10:
            try:
              current_station.orientation_corr = float(columns[10].strip())
            except Exception:
              current_station.orientation_corr = None

          if len(columns) > 11:
            try:
              current_station.edm_refractive_index = float(columns[11].strip())
            except Exception:
              current_station.edm_refractive_index = None

          current_station.description = line
          station_setups.append(current_station)

          is_new_station = False
          continue

        if current_station and len(columns) >= 15:
          raw_observation = RawObservation(
              id=random_id.int,
              target_name=columns[1].strip(),
              target_number=int(columns[0].strip()),
              circle=int(columns[6].strip()),
              hz_angle=float(columns[10].strip()),
              v_angle=float(columns[12].strip()),
              distance_geom=float(columns[7].strip())
          )

          try:
            raw_observation.target_height = float(columns[9].strip())
          except Exception:
            raw_observation.target_height = None

          try:
            raw_observation.prism_constant = float(columns[15].strip())
          except Exception:
            raw_observation.prism_constant = None

          try:
            raw_observation.pressure = float(columns[25].strip())
          except Exception:
            raw_observation.pressure = None

          try:
            raw_observation.temperature = float(columns[25].strip())
          except Exception:
            raw_observation.temperature = None

          try:
            raw_observation.std_dev_dist = float(columns[8].strip())
          except Exception:
            raw_observation.std_dev_dist = None

          try:
            raw_observation.std_dev_hz = float(columns[11].strip())
          except Exception:
            raw_observation.std_dev_hz = None

          try:
            raw_observation.std_dev_v = float(columns[13].strip())
          except Exception:
            raw_observation.std_dev_v = None

          try:
            raw_observation.refraction_coef = float(columns[16].strip())
          except Exception:
            raw_observation.refraction_coef = None

          if current_station.raw_observations is None:
            current_station.raw_observations = []
          current_station.raw_observations.append(raw_observation)

      import_session.station_setups = station_setups

      return import_session, station_setups

    except Exception as e:
      print(f"Ha ocurrido un error parseando el fichero: {e}")

