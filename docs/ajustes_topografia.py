import math
import statistics
from itertools import combinations


class KUTMAdjuster:
  def __init__(
    self,
    bessel_observations: list[BesselObservation],
    project: Project,
    import_session: ImportSession,
    station_setup: StationSetup

  ):
    self.bessel_observations = bessel_observations
    if not project.reference_coordinates:
      raise ValueError("No se encontraron observaciones Bessel")
    self.references_coordinates = project.reference_coordinates
    self.project = project
    self.import_session = import_session
    self.station_setup = station_setup

    self.filtered_refs: list[ReferenceCoordinate] = self._get_filtered_refs()
    self.etr_utm: tuple[float, float] = self.process_etr_utm()
    self.k_utm: float = self.calculate_k_utm()
    self.z_est: float = self.calculate_z_est()

  def calcula_inversa_xy_cassini(
    self,
    x1: float, y1: float, lh1: float,
    x2: float, y2: float, lh2: float,
    x3: float, y3: float, lh3: float
  ) -> tuple[float, float]:
    angulo_alfa = (lh2 - lh1) * self.project.gon_r
    angulo_beta = (lh3 - lh2) * self.project.gon_r

    x_a = x2 - x1 - (y2 - y1) / math.tan(angulo_alfa)
    x_b = y2 - y1 + (x2 - x1) / math.tan(angulo_alfa)
    x_c = x2 - x3 + (y2 - y3) / math.tan(angulo_beta)
    x_d = y2 - y3 - (x2 - x3) / math.tan(angulo_beta)
    x_e = (x_a * (x_b - x_d) - x_b * (x_a - x_c)) / (
        (x_a - x_c) ** 2 + (x_b - x_d) ** 2
    )

    x_teod = x2 - x_e * (x_b - x_d)
    y_teod = y2 + x_e * (x_a - x_c)

    return (x_teod, y_teod)

  def _get_filtered_refs(self) -> list[ReferenceCoordinate]:
    if not self.bessel_observations:
      raise ValueError("No se encontraron observaciones Bessel")

    bessel_names = [obs.target_name for obs in self.bessel_observations]
    filtered_refs = [
      ref
      for ref in self.references_coordinates
      if ref.target_name is not None and ref.target_name in bessel_names
    ]

    if len(filtered_refs) < 3:
      raise ValueError("Se necesitan al menos 3 puntos de referencia")

    return filtered_refs

  def process_etr_utm(self) -> tuple[float, float]:
    etr_coordinates: list[tuple[float, float]] = []

    for p1, p2, p3 in combinations(self.filtered_refs, 3):
      hz_angle_1: float | None = next(
          obs.hz_angle_bessel for obs in self.bessel_observations
          if obs.target_name == p1.target_name
      )
      hz_angle_2: float | None = next(
          obs.hz_angle_bessel for obs in self.bessel_observations
          if obs.target_name == p2.target_name
      )
      hz_angle_3: float | None = next(
          obs.hz_angle_bessel for obs in self.bessel_observations
          if obs.target_name == p3.target_name
      )

      try:
        if hz_angle_1 is None or hz_angle_2 is None or hz_angle_3 is None:
          raise ValueError('Alguno de los ángulos horizontales son nulos.')

        coord = self.calcula_inversa_xy_cassini(
          x1=p1.x, y1=p1.y, lh1=hz_angle_1,
          x2=p2.x, y2=p2.y, lh2=hz_angle_2,
          x3=p3.x, y3=p3.y, lh3=hz_angle_3
        )
        etr_coordinates.append(coord)

      except Exception as e:
        print(
          f"Error al calcular las coordenadas ETR para puntos {p1.target_name}, {p2.target_name}, {p3.target_name}: {str(e)}"
        )
        continue

    if not etr_coordinates:
      raise ValueError("No se pudieron calcular las coordenadas ETR")

    xs, ys = zip(*etr_coordinates)
    etr_x = statistics.mean(xs)
    etr_y = statistics.mean(ys)

    return etr_x, etr_y

  def calculate_k_utm(self) -> float:
    zone_utm_number = self.project.zona_utm[:-1]
    zone_utm_letter = self.project.zona_utm[-1]

    try:
      zone_utm_number = int(zone_utm_number)
    except ValueError:
      raise ValueError("El número de la zona UTM debe ser un entero")

    if zone_utm_letter not in "CDEFGHJKLMNPQRSTUVWX":
      raise ValueError("La letra de la zona UTM debe ser una letra válida")

    J8 = (self.etr_utm[0] - 500000) / self.project.k_0_adim
    J9 = (
      self.etr_utm[1] / self.project.k_0_adim
      if zone_utm_letter in "CDEFGHJKLM"
      else (self.etr_utm[1] - 10000000) / self.project.k_0_adim
    )

    B10 = self.project.f_m * (2 - self.project.f_m)
    B11 = (self.project.a_m**2 - self.project.b_m**2) / (self.project.b_m**2)
    B16 = B10**2
    B17 = B10**3

    F21 = 1 + (3 / 4) * B10 + (45 / 64) * B16 + (175 / 256) * B17
    F22 = (3 / 4) * B10 + (15 / 16) * B16 + (525 / 512) * B17
    F23 = (15 / 64) * B16 + (105 / 256) * B17
    F24 = (35 / 512) * B17

    I21 = F21 * self.project.a_m * (1 - B10)
    I22 = (F22 / 2) * self.project.a_m * (1 - B10)
    I23 = (F23 / 4) * self.project.a_m * (1 - B10)
    I24 = (F24 / 6) * self.project.a_m * (1 - B10)

    O3 = J9 / I21
    O4 = (
      J9
      + I22 * math.sin(2 * O3)
      - I23 * math.sin(4 * O3)
      + I24 * math.sin(6 * O3)
    ) / I21
    O5 = (
      J9
      + I22 * math.sin(2 * O4)
      - I23 * math.sin(4 * O4)
      + I24 * math.sin(6 * O4)
    ) / I21
    O6 = (
      J9
      + I22 * math.sin(2 * O5)
      - I23 * math.sin(4 * O5)
      + I24 * math.sin(6 * O5)
    ) / I21

    J14 = (self.project.a_m * (1 - B10)) / (1 - B10 * (math.sin(O6) ** 2)) ** (3 / 2)
    J13 = self.project.a_m / math.sqrt(1 - B10 * (math.sin(O6) ** 2))

    B14 = B11 * (math.cos(O6) ** 2)
    B18 = B14**2
    B19 = B14**3

    k_prima = (
      1
      + (J8**2) / (2 * J14 * J13)
      + (J8**4)
      / (24 * J13**4)
      * (
        1
        + 6 * B14
        + 9 * B18
        - 24 * (math.tan(O6) ** 2) * B18
        + 4 * B19
        - 24 * (math.tan(O6) ** 2) * B19
      )
    )

    return k_prima * self.project.k_0_adim

  def calculate_z_est(self) -> float:
    z_prima_refs: list[float] = []
    z_refs: list[float] = []
    dist_reducidas: dict[str, float] = {}
    v_angle_bessels: dict[str, float] = {
        obs.target_name: obs.v_angle_bessel
        for obs in self.bessel_observations
    }

    for ref in self.filtered_refs:
      x_ref = ref.x
      y_ref = ref.y
      z_ref = ref.z

      if not self.station_setup.raw_observations:
        raise ValueError("No se encontraron observaciones brutas")

      i = next(
          raw_obs.i for raw_obs in self.station_setup.raw_observations
          if raw_obs.target_name == ref.target_name
      )
      m = next(
          raw_obs.m for raw_obs in self.station_setup.raw_observations
          if raw_obs.target_name == ref.target_name
      )
      v_angle_bessel = v_angle_bessels[ref.target_name]

      delta_E = x_ref - self.etr_utm[0]
      delta_N = y_ref - self.etr_utm[1]
      dist_calculada = math.hypot(delta_E, delta_N)
      dist_reducida = dist_calculada / self.k_utm
      dist_reducidas[ref.target_name] = dist_reducida
      delta_Z = (
        dist_reducida * math.cos(v_angle_bessel * self.project.gon_r)
        + (i - m)
        + (0.5 - self.import_session.kt_coef_refr) * (dist_reducida**2) / self.project.radio_tierra
      )
      z_prima = z_ref - delta_Z

      z_prima_refs.append(z_prima)

    z_prima_promedio = statistics.mean(z_prima_refs)

    for ref in self.filtered_refs:
      dist_reducida = dist_reducidas[ref.target_name]
      v_angle_bessel = v_angle_bessels[ref.target_name]
      if not self.station_setup.raw_observations:
        raise ValueError("No se encontraron observaciones brutas")

      i = next(
          raw_obs.i for raw_obs in self.station_setup.raw_observations
          if raw_obs.target_name == ref.target_name
      )
      m = next(
          raw_obs.m for raw_obs in self.station_setup.raw_observations
          if raw_obs.target_name == ref.target_name
      )

      dist_red_elipsoide = (
        dist_reducida
        * (z_prima_promedio + self.project.radio_tierra)
        / self.project.radio_tierra
      )
      delta_z = (
        dist_red_elipsoide * math.cos(v_angle_bessel * self.project.gon_r)
        + (i - m)
        + (0.5 - self.import_session.kt_coef_refr)
        * (dist_red_elipsoide**2)
        / self.project.radio_tierra
      )
      z = ref.z - delta_z

      z_refs.append(z)

    omega_alpha_cc = (self.import_session.prec_ang_etr * self.project.s_sexa_s_gon) ** 2
    z_est = (sum(z_refs) / omega_alpha_cc) / ((1 / omega_alpha_cc) * len(z_refs))

    return z_est


